"""Build an isolated native picker probe; not a production storage adapter."""
from build_shortcuts import Flow, WORK, var, token
from native_manager import choose, assert_has

WORK.mkdir(exist_ok=True)
f = Flow()
f.a('comment', WFCommentActionText='诊断版2：检查保存输出，并独立选择文件验证。不读写 ColaManager 正式数据，不保证固定目录权限。')
choose(f, 'mode', ['创建独立测试文件', '重新读取测试文件'], '请关闭 iCloud Drive 并选择“我的 iPhone”位置')
g = f.iff(var('mode'), 4, '创建独立测试文件')
f.text('payload', '{"probe":"ColaManager-local-v2","value":42}')
f.a('alert', WFAlertActionTitle='第1步：选择本地保存位置', WFAlertActionMessage='接下来应出现保存界面。请选择“浏览→我的 iPhone”下可用的文件夹并点存储。文件名为 ColaManager-local-probe-v2.json。若未出现保存界面，请记录这个现象。', WFAlertActionCancelButtonShown=True)
named = f.a('setitemname', WFInput=var('payload'), WFName='ColaManager-local-probe-v2.json')
f.set('saved', f.a('documentpicker.save', WFInput=named, WFAskWhereToSave=True, WFSaveFileOverwrite=False))
assert_has(f, var('saved'), '保存动作没有返回文件，无法确认保存。请反馈是否出现保存位置选择器。本次不报告成功。')
f.set('saved_text', f.a('gettext', WFTextActionText=token(var('saved'))))
h = f.iff(var('saved_text'), 5, token(var('payload')))
f.stop('保存动作返回的内容与测试内容不一致，未通过校验。请反馈保存界面是否出现及所选位置。')
f.end(h)
f.a('alert', WFAlertActionTitle='第2步：独立查找文件', WFAlertActionMessage='保存输出内容匹配，但尚未证明文件落盘。接下来请在文件选择器中，进入刚才的“我的 iPhone”文件夹，选择 ColaManager-local-probe-v2.json。若不存在，请取消并反馈。', WFAlertActionCancelButtonShown=True)
f.end(g)
f.set('picked', f.a('file.select', SelectMultiple=False))
assert_has(f, var('picked'), '没有选到文件，未通过持久化验证。')
f.set('data', f.a('detect.dictionary', WFInput=var('picked')))
f.get('marker', var('data'), 'probe')
g = f.iff(var('marker'), 5, 'ColaManager-local-v2')
f.stop('不是此探针生成的测试文件。没有修改任何文件。')
f.end(g)
f.get('value', var('data'), 'value')
g = f.iff(var('value'), 5, 42)
f.stop('读取值不符合预期。没有修改任何文件。')
f.end(g)
f.show('独立选择的文件内容校验通过。请退出后选择“重新读取测试文件”，再重启 iPhone 重测。只有保存位置确认为“我的 iPhone”，才能算本地验证；本探针不能自动识别文件提供方，不验证固定目录免交互访问。')
f.output('ColaManager-Local-Probe-v2')
